/**
 * @file    bsp_fwdgt.h
 * @brief   独立看门狗（FWDGT）BSP 驱动接口
 *
 * @note    独立看门狗使用独立 RC 振荡器，不依赖系统时钟。
 *          超时前必须周期喂狗，否则系统复位。
 */
#ifndef __BSP_FWDGT_H__
#define __BSP_FWDGT_H__

#include "config.h"

/************************************************************
 * @brief   初始化独立看门狗
 * @retval  RET_OK 成功
 * @note    配置为重载值 3124、128 分频，约 1s 超时
 ************************************************************/
ret_t bsp_fwdgt_init(void);

/************************************************************
 * @brief   喂狗（重载计数器）
 * @retval  RET_OK 成功
 ************************************************************/
ret_t bsp_fwdgt_feed(void);

#endif /* __BSP_FWDGT_H__ */
